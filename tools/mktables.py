#!/usr/bin/env python3
# SCAFFOLD (M1): generate nasm0's keyword tables and prove the name hashes do not collide.
# Hash (computable in NaN16 with SHL/ADD only):  h = 5381; for c in name: h = (h<<5) + h + c   (mod 2^32)
# Writes src/prog/nasm0_tables.nas  (mnem: hash,op,form | preds: hash,n | dirs: hash,id), sentinel hash 0.
# Form nibbles, first operand in the low nibble: 1=d 2=a 3=b(rN into imm[3:0]) 4=i(imm16 expression).
import sys,os,re
sys.path.insert(0,os.path.dirname(__file__))
import nanchk
M=0xFFFFFFFF
def h(s):
    x=5381
    for c in s.encode(): x=((x<<5)+x+c)&M
    return x
KIND={'d':1,'a':2,'b':3,'i':4}
def form(f):
    v=0
    for i,c in enumerate(f): v|=KIND[c]<<(4*i)
    return v
DIRS={'word':1,'str':2,'equ':3}
def corpus_names(paths):
    names=set()
    for p in paths:
        for raw in nanchk.readsrc(p):
            t=raw.split(';')[0].strip()
            m=re.match(r'(\w+):$',t)
            if m: names.add(m.group(1))
            if t.startswith('.equ'): names.add(t.split()[1])
    return names
def check(groups):
    ok=True
    for gname,names in groups.items():
        seen={}
        for n in sorted(names):
            x=h(n)
            if x==0: print('ZERO HASH',gname,n); ok=False
            if x in seen: print('COLLISION',gname,n,seen[x]); ok=False
            seen[x]=n
    return ok
def main():
    root=os.path.join(os.path.dirname(__file__),'..')
    srcs=sys.argv[1:] or [os.path.join(root,'src/museum/museum.nas'),os.path.join(root,'src/prog/selftest.nas'),os.path.join(root,'src/prog/sierpinski.nas'),os.path.join(root,'src/prog/nasm0_proof.nas')]
    srcs=[s for s in srcs if os.path.exists(s)]
    names=corpus_names(srcs)
    groups={'mnemonics':set(nanchk.OPS),'preds':set(nanchk.PRED),'dirs':set(DIRS),'names(labels+equ)':names}
    ok=check(groups)
    print('names checked:',len(names),'from',len(srcs),'sources; collisions:', 'NONE' if ok else 'FOUND')
    if not ok: sys.exit(1)
    out=['; GENERATED by tools/mktables.py - do not edit. hash h=(h<<5)+h+c from 5381; entries end with hash 0.',
         'mnem:']
    for k,v in nanchk.OPS.items(): out.append('.word %d,%d,%d   ; %s %s'%(h(k),v,form(nanchk.FORM[k]),k,nanchk.FORM[k]))
    out+=['.word 0,0,0','preds:']
    for k,v in nanchk.PRED.items(): out.append('.word %d,%d   ; %s'%(h(k),v,k))
    out+=['.word 0,0','dirs:']
    for k,v in DIRS.items(): out.append('.word %d,%d   ; .%s'%(h(k),v,k))
    out+=['.word 0,0']
    open(os.path.join(root,'src/prog/nasm0_tables.nas'),'w').write('\n'.join(out)+'\n')
    print('wrote src/prog/nasm0_tables.nas: %d mnemonics, %d preds, %d dirs'%(len(nanchk.OPS),len(nanchk.PRED),len(DIRS)))
main()
