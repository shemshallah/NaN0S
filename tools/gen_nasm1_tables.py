#!/usr/bin/env python3
# SCAFFOLD (not NaN/0S): generate nasm1 hash tables (djb2 5381, case-folded to upper).
def h(s):
    x=5381
    for c in s.upper(): x=((x*33)+ord(c))&0xFFFFFFFF
    return x
M=[
 ('NOP','h_byte1',0x90),('HLT','h_byte1',0xF4),('RET','h_byte1',0xC3),('CLC','h_byte1',0xF8),
 ('STC','h_byte1',0xF9),('CLD','h_byte1',0xFC),('STD','h_byte1',0xFD),('CLI','h_byte1',0xFA),
 ('STI','h_byte1',0xFB),('CLTD','h_byte1',0x99),
 ('MOV','m_mov',0),('MOVB','m_movb',0),('MOVW','m_movw',0),('MOVL','m_movl',0),
 ('MOVZX','h_movzx',0),('MOVZXB','h_movzx',0xB6),('MOVZXW','h_movzx',0xB7),
 ('MOVSX','h_movsx',0),('MOVSXB','h_movsx',0xBE),('MOVSXW','h_movsx',0xBF),
 ('ADD','h_alu',0|(0x00<<8)),('OR','h_alu',1|(0x08<<8)),('AND','h_alu',4|(0x20<<8)),
 ('SUB','h_alu',5|(0x28<<8)),('XOR','h_alu',6|(0x30<<8)),('CMP','h_alu',7|(0x38<<8)),
 ('TEST','h_test',0),('INC','h_incdec',0),('DEC','h_incdec',1),
 ('NOT','h_group',2),('NEG','h_group',3),('MUL','h_group',4),('IMUL','m_imul',5),
 ('DIV','h_group',6),('IDIV','h_group',7),
 ('SHL','h_shift',4),('SAL','h_shift',4),('SHR','h_shift',5),('SAR','h_shift',7),
 ('ROL','h_shift',0),('ROR','h_shift',1),
 ('JMP','m_jmp',0),('CALL','m_call',0),('LOOP','m_loop',0),('JECXZ','m_jecxz',0),
 ('PUSH','h_pushpop',0),('POP','h_pushpop',1),('LEA','h_lea',0),('IN','m_inout',0),
 ('OUT','m_inout',0),('INT','m_int',0),('LGDT','h_gdt',2),('LIDT','h_gdt',3),
 ('LJMP','m_ljmp',0),('SHRD','m_shrd',0),('BT','m_bt',0),('BSWAP','m_bswap',0),
 ('ADDSS','h_sse3',0x58),('SUBSS','h_sse3',0x5C),('MULSS','h_sse3',0x59),('DIVSS','h_sse3',0x5E),
 ('SQRTSS','h_sse3',0x51),('UCOMISS','h_sse0',0x2E),('XORPS','h_sse0',0x57),
 ('CVTSI2SS','h_cvt',0x2A),('CVTTSS2SI','h_cvt',0x2C),
 ('MOVD','m_movd',0),('MOVQL','m_movql',0),('MOVQS','m_movqs',0),('MOVQ','h_movq',0),
 ('MOVZBL','h_movzx',0xB6),('MOVZWL','h_movzx',0xB7),('MOVSBL','h_movsx',0xBE),('MOVSWL','h_movsx',0xBF),
 ('IMUL2','m_imul',0),
 ('REPSTOSD','h_rep',0xAB),('REPMOVSD','h_rep',0xA5),
]
SETS=[('SETO',0),('SETNO',1),('SETB',2),('SETC',2),('SETAE',3),('SETNC',3),('SETE',4),('SETZ',4),('SETNE',5),('SETNZ',5),('SETBE',6),('SETA',7),('SETS',8),('SETNS',9),('SETP',10),('SETNP',11),('SETL',12),('SETGE',13),('SETLE',14),('SETG',15)]

ALUP={'ADD':0,'OR':1|(0x08<<8),'AND':4|(0x20<<8),'SUB':5|(0x28<<8),'XOR':6|(0x30<<8),'CMP':7|(0x38<<8)}
SHGP={'SHL':4,'SAL':4,'SHR':5,'SAR':7,'ROL':0,'ROR':1}
GRP={'NOT':2,'NEG':3,'MUL':4,'DIV':6,'IDIV':7}
for suf,sz in (('B','b'),('W','w'),('L','l')):
    M.append(('INC'+suf,'m_inc_'+sz,0))
    M.append(('DEC'+suf,'m_inc_'+sz,1))
    for k,v in ALUP.items(): M.append((k+suf,'m_alu_'+sz,v))
    M.append(('TEST'+suf,'m_test_'+sz,0))
    for k,v in SHGP.items(): M.append((k+suf,'m_shift_'+sz,v))
    for k,v in GRP.items(): M.append((k+suf,'m_group_'+sz,v))
    M.append(('IMUL'+suf,'m_imul_'+sz,5))
J={'JO':0,'JNO':1,'JB':2,'JC':2,'JAE':3,'JNC':3,'JE':4,'JZ':4,'JNE':5,'JNZ':5,'JBE':6,'JA':7,
   'JS':8,'JNS':9,'JP':10,'JNP':11,'JL':12,'JGE':13,'JLE':14,'JG':15}
R={'EAX':0x20,'ECX':0x21,'EDX':0x22,'EBX':0x23,'ESP':0x24,'EBP':0x25,'ESI':0x26,'EDI':0x27,
 'AX':0x10,'CX':0x11,'DX':0x12,'BX':0x13,'SP':0x14,'BP':0x15,'SI':0x16,'DI':0x17,
 'AL':0x00,'CL':0x01,'DL':0x02,'BL':0x03,'AH':0x04,'CH':0x05,'DH':0x06,'BH':0x07,
 'ES':0x50,'CS':0x51,'SS':0x52,'DS':0x53,'FS':0x54,'GS':0x55,'CR0':0x40,'CR2':0x42,'CR3':0x43}
for i in range(8): R['XMM%d'%i]=0x30+i
D=[('byte','d_byte'),('word','d_word'),('long','d_long'),('str','d_str'),('equ','d_equ'),
   ('org','d_org'),('align','d_align'),('base','d_base'),('code16','d_code16'),('code32','d_code32')]
L=['; nasm1_tables.nas - generated by tools/gen_nasm1_tables.py; djb2 5381, case-folded. Do not edit by hand.','mnem:']
for k,fn,p in M: L.append('.word %d,@%s,%d   ; %s'%(h(k),fn,p,k))
for k,cc in J.items(): L.append('.word %d,@h_jcc,%d   ; %s'%(h(k),cc,k))
for k,cc in SETS: L.append('.word %d,@h_setcc,%d   ; %s'%(h(k),cc,k))
L.append('.word 0,0,0')
L.append('regs:')
for k,v in R.items(): L.append('.word %d,%d   ; %s'%(h(k),v,k))
L.append('.word 0,0')
L.append('dirs:')
for k,fn in D: L.append('.word %d,@%s,0   ; .%s'%(h(k),fn,k))
L.append('.word 0,0,0')
open('src/prog/nasm1_tables.nas','w').write('\n'.join(L)+'\n')
print('mnem',len(M)+len(J),'regs',len(R),'dirs',len(D))
