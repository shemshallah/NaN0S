#!/usr/bin/env python3
# SCAFFOLD: emit the Baby store images (.word lines) for N=2^18 (authentic scale) and N=2^12 (quick demo) from the verified reference model.
import sys; sys.path.insert(0,'tools')
import babyref
out=['; GENERATED by tools/mkbabydata.py from tools/babyref.py - Baby store images (32 words each). Program = highest proper factor, 20 instructions.']
for lab,N in (('baby18',2**18),('baby12',2**12)):
    st,L=babyref.program(N)
    out.append('%s:   ; N=%d'%(lab,N))
    for i,w in enumerate(st): out.append('.word 0x%08X   ; line %02d'%(w,i))
open('src/museum/baby_data.nas','w').write('\n'.join(out)+'\n'); print('baby_data.nas written')
