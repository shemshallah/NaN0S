    out=['; font7.nas - NaNGlyph 7x11 stroke font (generated by tools/gen_font.py from original stroke definitions). 95 glyphs x 11 row words, bit6 = leftmost.','; cell 8x13: advance 8, row pitch 13.','font7:']
    rows=[]
    for code in range(32,127):
        bm=raster(chr(code)); rows.append(bm)
        out.append('; %r'%chr(code))
        for r in bm: out.append('.word %d'%int(''.join(map(str,r)),2))
    open('src/lib/font7.nas','w').write('\n'.join(out)+'\n')
