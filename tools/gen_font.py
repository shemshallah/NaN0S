W,H=7,11
def line(bm,a,b):
    (x0,y0),(x1,y1)=a,b
    dx,dy=abs(x1-x0),-abs(y1-y0); sx=1 if x0<x1 else -1; sy=1 if y0<y1 else -1; e=dx+dy
    while True:
        bm[y0][x0]=1
        if (x0,y0)==(x1,y1): break
        e2=2*e
        if e2>=dy: e+=dy; x0+=sx
        if e2<=dx: e+=dx; y0+=sy
def raster(c):
    bm=[[0]*W for _ in range(H)]
    for st in G[c]:
        if len(st)==1: bm[st[0][1]][st[0][0]]=1
        for a,b in zip(st,st[1:]): line(bm,a,b)
    return bm
